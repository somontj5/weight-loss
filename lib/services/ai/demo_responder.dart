import 'dart:math';


/// Демо-режим без ключа/сети: отвечает заготовками по ключевым словам.
class DemoResponder {
  final _rnd = Random();

  Future<String> reply({
    required String text,
    required List<String> imagePaths,
    Duration? audioDuration,
  }) async {
    await Future<void>.delayed(
        Duration(milliseconds: 1100 + _rnd.nextInt(900)));

    final t = text.toLowerCase();
    final parts = <String>[];

    if (imagePaths.isNotEmpty) {
      final n = imagePaths.length;
      parts.add(n == 1
          ? 'Фото получил! Пока я работаю в демо-режиме и не вижу, что на нём, но скоро научусь считать калории по снимку.'
          : 'Получил $n фото! Пока я работаю в демо-режиме и не вижу, что на них, но скоро научусь разбирать блюда и считать калории.');
    }

    if (audioDuration != null) {
      final s = audioDuration.inSeconds;
      parts.add(
          'Услышал твоё голосовое на $s сек. Расшифровку speech-to-text подключим вместе с настоящим ИИ.');
    }

    if (t.isNotEmpty) {
      parts.add(_byKeyword(t));
    } else if (parts.isNotEmpty) {
      parts.add('Расскажи, что у тебя на сердце — и разберём вместе.');
    }

    return parts.join('\n\n');
  }

  String _byKeyword(String t) {
    bool has(List<String> w) => w.any(t.contains);

    if (has(['привет', 'здравств', 'хай', 'добрый'])) {
      return 'Привет! Рад тебя видеть. С чего начнём: питание, тренировка или мотивация?';
    }
    if (has(['план', 'меню', 'рацион', 'диет'])) {
      return 'Давай соберём простой план на день:\n\n'
          '• Завтрак: овсянка с ягодами и яйцо\n'
          '• Обед: курица или рыба, гарнир из овощей\n'
          '• Перекус: творог или яблоко\n'
          '• Ужин: лёгкий салат с белком\n\n'
          'Скажи свой рост, вес и цель — подгоню калории точнее.';
    }
    if (has(['калори', 'ккал', 'сколько съесть'])) {
      return 'Для старта обычно берут дефицит 10–20% от суточной нормы. Напиши рост, вес, возраст и уровень активности — прикину твою цифру.';
    }
    if (has(['трен', 'упражн', 'зал', 'кардио', 'бег'])) {
      return 'Отличный настрой! Для начала хватит 3 тренировок в неделю по 30 минут: быстрая ходьба или лёгкий бег плюс базовые упражнения с весом тела. Главное — регулярность.';
    }
    if (has(['устал', 'лень', 'не хочу', 'срыв', 'сорвал', 'съел'])) {
      return 'Эй, всё нормально. Один срыв ничего не ломает — важно, что ты вернёшься к плану уже со следующего приёма пищи. Я с тобой.';
    }
    if (has(['вода', 'пить', 'воды'])) {
      return 'Вода помогает контролировать аппетит. Ориентир — около 30 мл на килограмм веса. Начни со стакана перед каждым приёмом пищи.';
    }
    if (has(['мотив', 'поддерж', 'вдохнов'])) {
      return 'Ты уже делаешь главное — идёшь к цели. Маленькие шаги каждый день дают большой результат. Сегодня просто выпей воды и пройдись 15 минут. Договорились?';
    }
    if (has(['спасибо', 'благодар'])) {
      return 'Всегда пожалуйста! Я рядом, когда понадоблюсь.';
    }
    if (has(['вес', 'похуд', 'кг'])) {
      return 'Здоровый темп — 0,5–1 кг в неделю. Давай поставим цель: сколько хочешь сбросить и к какому сроку?';
    }
    const generic = [
      'Понял тебя! Расскажи чуть подробнее, и я подберу совет под твою ситуацию.',
      'Интересно! А как у тебя сейчас с питанием и активностью в течение дня?',
      'Хороший вопрос. Давай разберём по шагам — с чего хочешь начать?',
    ];
    return generic[_rnd.nextInt(generic.length)];
  }
}
