/// Ротация текстов без повтора подряд. Индекс зависит только от дня и слота,
/// поэтому он стабилен при пересоздании расписания, а в два соседних дня
/// один и тот же вариант не выпадает (если вариантов больше одного).
class TextRotator {
  static int forDay({required int count, required DateTime day, int seed = 0}) {
    if (count <= 1) return 0;
    final n =
        DateTime.utc(
          day.year,
          day.month,
          day.day,
        ).difference(DateTime.utc(2020)).inDays +
        seed * 3;
    return n % count;
  }
}
